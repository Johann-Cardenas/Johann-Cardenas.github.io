/* Characters that keep their own case; everything else is upper-cased,
   because none of these faces has lowercase forms. */
export const CASED = new Set(['σ', 'ε', 'µ', '·', '°', '×', '−']);

/**
 * Every glyph must have exactly `h` rows and fit inside `w` columns, and
 * every face must cover the same character set — otherwise a banner
 * silently loses letters. Each generator calls this before it draws.
 */
export function validateFonts() {
    const fail = [];
    const base = Object.keys(FONTS.terminal.glyphs).filter(c => c !== '=');
    for (const f of Object.values(FONTS)) {
        const max = (1 << f.w) - 1;
        for (const [ch, rows] of Object.entries(f.glyphs)) {
            if (rows.length !== f.h) fail.push(`${f.name} '${ch}': ${rows.length} rows, expected ${f.h}`);
            rows.forEach((r, i) => {
                if (r < 0 || r > max) fail.push(`${f.name} '${ch}' row ${i}: 0x${r.toString(16)} exceeds ${f.w} columns`);
            });
        }
        for (const ch of base) if (!(ch in f.glyphs)) fail.push(`${f.name} is missing '${ch}'`);
    }
    if (fail.length) {
        console.error('Font tables are broken:\n  ' + fail.join('\n  '));
        process.exit(1);
    }
}
